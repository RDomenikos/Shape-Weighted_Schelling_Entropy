#!/usr/bin/env python3
"""
Create the main paper figures from outputs generated by run_paper_batch.py.

Typical use
-----------
python plot_paper_figures.py --results results_paper

Figures written
---------------
fig1_lattice_snapshots.png
fig2_histograms_scenario3.png
fig3_entropy_comparison.png
fig4_shape_weights.png
fig5_ablation_correlations.png
fig6_scenario4_freezing.png
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Dict, Iterable, List, Optional

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from simulation_model import SimulationParams
from entropy_metrics import classify_microstates, histogram_C_by_state


def load_params(json_path: Path) -> SimulationParams:
    with open(json_path, "r", encoding="utf-8") as f:
        d = json.load(f)
    return SimulationParams(
        scenario=int(d["scenario"]),
        N=int(d["N"]),
        steps=int(d["steps"]),
        vacancy=float(d["vacancy"]),
        R_move=int(d["R_move"]),
        happy_threshold=int(d["happy_threshold"]),
        C_range=(int(d["C_range"][0]), int(d["C_range"][1])),
        M_range=(float(d["M_range"][0]), float(d["M_range"][1])),
        X_move=float(d["X_move"]),
        X_call=float(d["X_call"]),
        calls_per_agent=int(d["calls_per_agent"]),
        seed_positions=int(d["seed_positions"]),
        seed_affil=int(d["seed_affil"]),
        seed_money=int(d["seed_money"]),
        seed_dynamics=int(d["seed_dynamics"]),
    )


def load_representative(results_dir: Path, scenario: int):
    npz_path = results_dir / "representative_npz" / f"scenario_{scenario}_representative.npz"
    params_path = npz_path.with_suffix(".params.json")
    if not npz_path.exists():
        raise FileNotFoundError(f"Missing representative run: {npz_path}")
    data = np.load(npz_path)
    params = load_params(params_path)
    return data["C_history"], data["M_history"], params


def mean_col(summary: pd.DataFrame, name: str) -> str:
    c = f"{name}_mean"
    if c not in summary.columns:
        raise KeyError(f"Missing column {c} in summary_timeseries.csv")
    return c


def plot_with_ci(ax, df: pd.DataFrame, variable: str, label: str) -> None:
    x = df["step"].to_numpy()
    y = df[f"{variable}_mean"].to_numpy()
    lo = df.get(f"{variable}_ci95_low", pd.Series(np.nan, index=df.index)).to_numpy()
    hi = df.get(f"{variable}_ci95_high", pd.Series(np.nan, index=df.index)).to_numpy()
    ax.plot(x, y, label=label)
    if np.isfinite(lo).any() and np.isfinite(hi).any():
        ax.fill_between(x, lo, hi, alpha=0.2)


def make_fig1_snapshots(results_dir: Path, out_dir: Path, snapshot_steps: Optional[List[int]] = None) -> None:
    scenarios = [1, 2, 3, 4]
    histories = {}
    params_by_s = {}
    for s in scenarios:
        C_hist, _M_hist, params = load_representative(results_dir, s)
        histories[s] = C_hist
        params_by_s[s] = params

    max_steps = min(h.shape[0] - 1 for h in histories.values())
    if snapshot_steps is None:
        snapshot_steps = [0, max(1, max_steps // 10), max_steps // 2, max_steps]
    snapshot_steps = [min(max_steps, int(t)) for t in snapshot_steps]

    fig, axes = plt.subplots(len(scenarios), len(snapshot_steps), figsize=(3.2 * len(snapshot_steps), 3.2 * len(scenarios)))
    if axes.ndim == 1:
        axes = axes.reshape(len(scenarios), len(snapshot_steps))

    vmin = min(params.C_range[0] for params in params_by_s.values())
    vmax = max(params.C_range[1] for params in params_by_s.values())

    for r, s in enumerate(scenarios):
        C_hist = histories[s]
        for c, t in enumerate(snapshot_steps):
            ax = axes[r, c]
            im = ax.imshow(C_hist[t], vmin=vmin, vmax=vmax, interpolation="nearest")
            ax.set_xticks([])
            ax.set_yticks([])
            if r == 0:
                ax.set_title(f"step {t}")
            if c == 0:
                ax.set_ylabel(f"Scenario {s}")
    fig.colorbar(im, ax=axes.ravel().tolist(), shrink=0.75, label="C")
    fig.suptitle("Representative affiliation-field evolution", y=0.995)
    fig.savefig(out_dir / "fig1_lattice_snapshots.png", dpi=300, bbox_inches="tight")
    plt.close(fig)


def make_fig2_histograms_scenario3(results_dir: Path, out_dir: Path, snapshot_steps: Optional[List[int]] = None) -> None:
    C_hist, M_hist, params = load_representative(results_dir, 3)
    max_steps = C_hist.shape[0] - 1
    if snapshot_steps is None:
        snapshot_steps = [0, max(1, max_steps // 10), max_steps // 2, max_steps]
    snapshot_steps = [min(max_steps, int(t)) for t in snapshot_steps]

    C_min, C_max = params.C_range
    grid = np.arange(C_min, C_max + 1)
    microstates = ["B", "A", "T"]

    fig, axes = plt.subplots(len(microstates), len(snapshot_steps), figsize=(3.4 * len(snapshot_steps), 2.7 * len(microstates)), sharex=True)
    for r, key in enumerate(microstates):
        for c, t in enumerate(snapshot_steps):
            st = classify_microstates(C_hist[t], M_hist[t], params)
            hists = histogram_C_by_state(C_hist[t], st, C_min, C_max, alpha=0.5)
            counts = hists[key]["counts"]
            total = counts.sum()
            density = counts / total if total > 0 else counts
            ax = axes[r, c]
            ax.bar(grid, density, width=0.9)
            if r == 0:
                ax.set_title(f"step {t}")
            if c == 0:
                ax.set_ylabel(f"{key}\ndensity")
            ax.set_xlim(C_min - 0.5, C_max + 0.5)
    for ax in axes[-1, :]:
        ax.set_xlabel("C")
    fig.suptitle("Scenario 3: microstate histograms of affiliation C", y=1.02)
    fig.savefig(out_dir / "fig2_histograms_scenario3.png", dpi=300, bbox_inches="tight")
    plt.close(fig)


def make_fig3_entropy_comparison(summary: pd.DataFrame, out_dir: Path) -> None:
    scenarios = sorted(summary["scenario"].unique())
    fig, axes = plt.subplots(len(scenarios), 1, figsize=(8.5, 2.4 * len(scenarios)), sharex=True)
    if len(scenarios) == 1:
        axes = [axes]
    for ax, s in zip(axes, scenarios):
        df = summary[summary["scenario"] == s]
        plot_with_ci(ax, df, "S_shannon_lattice", "Shannon lattice entropy")
        plot_with_ci(ax, df, "S_full_lattice", "Shape-weighted entropy")
        ax.set_ylabel(f"Scenario {s}\nentropy")
        ax.grid(True, alpha=0.25)
        ax.legend(loc="best")
    axes[-1].set_xlabel("Step")
    fig.suptitle("Shannon versus shape-weighted entropy", y=0.995)
    fig.savefig(out_dir / "fig3_entropy_comparison.png", dpi=300, bbox_inches="tight")
    plt.close(fig)


def make_fig4_shape_weights(summary: pd.DataFrame, out_dir: Path) -> None:
    scenarios = sorted(summary["scenario"].unique())
    fig, axes = plt.subplots(len(scenarios), 1, figsize=(8.5, 2.4 * len(scenarios)), sharex=True)
    if len(scenarios) == 1:
        axes = [axes]
    for ax, s in zip(axes, scenarios):
        df = summary[summary["scenario"] == s]
        for var, label in [("wN_lattice", "normality"), ("wT_lattice", "heavy-tail"), ("wB_lattice", "bimodality")]:
            plot_with_ci(ax, df, var, label)
        ax.set_ylim(-0.05, 1.05)
        ax.set_ylabel(f"Scenario {s}\nweight")
        ax.grid(True, alpha=0.25)
        ax.legend(loc="best")
    axes[-1].set_xlabel("Step")
    fig.suptitle("Lattice-averaged shape weights", y=0.995)
    fig.savefig(out_dir / "fig4_shape_weights.png", dpi=300, bbox_inches="tight")
    plt.close(fig)


def make_fig5_ablation_correlations(corr: pd.DataFrame, out_dir: Path) -> None:
    if corr.empty:
        return
    diagnostics = [
        "S_shannon_lattice",
        "S_tail_ablation_lattice",
        "S_bimodal_ablation_lattice",
        "S_full_lattice",
        "wB_lattice",
    ]
    target = "polarization"
    df = corr[(corr["target"] == target) & (corr["diagnostic"].isin(diagnostics))].copy()
    if df.empty:
        return

    scenarios = sorted(df["scenario"].unique())
    x = np.arange(len(diagnostics))
    width = 0.8 / max(1, len(scenarios))

    fig, ax = plt.subplots(figsize=(11, 5))
    for k, s in enumerate(scenarios):
        d = df[df["scenario"] == s].set_index("diagnostic").reindex(diagnostics)
        offset = (k - (len(scenarios) - 1) / 2) * width
        ax.bar(x + offset, d["r_mean"].to_numpy(), width=width, label=f"Scenario {s}")
    ax.axhline(0, linewidth=1)
    ax.set_xticks(x)
    ax.set_xticklabels([
        "Shannon",
        "Shannon+tail",
        "Shannon+bimodal",
        "Full entropy",
        "bimodality weight",
    ], rotation=20, ha="right")
    ax.set_ylabel("mean within-run correlation with polarization")
    ax.set_title("Ablation / diagnostic comparison")
    ax.grid(True, axis="y", alpha=0.25)
    ax.legend(loc="best")
    fig.savefig(out_dir / "fig5_ablation_correlations.png", dpi=300, bbox_inches="tight")
    plt.close(fig)


def make_fig6_scenario4_freezing(summary: pd.DataFrame, out_dir: Path) -> None:
    df = summary[summary["scenario"] == 4].copy()
    if df.empty:
        return
    variables = [
        ("qT", "trapped fraction $q_T$"),
        ("moves_made", "moves made per step"),
        ("mean_money", "mean money"),
        ("S_full_lattice", "shape-weighted entropy"),
    ]
    fig, axes = plt.subplots(len(variables), 1, figsize=(8.5, 8.5), sharex=True)
    for ax, (var, label) in zip(axes, variables):
        if f"{var}_mean" not in df.columns:
            ax.text(0.5, 0.5, f"Missing {var}", ha="center", va="center")
            continue
        plot_with_ci(ax, df, var, label)
        ax.set_ylabel(label)
        ax.grid(True, alpha=0.25)
    axes[-1].set_xlabel("Step")
    fig.suptitle("Scenario 4: economic freezing and entropy stabilization", y=0.995)
    fig.savefig(out_dir / "fig6_scenario4_freezing.png", dpi=300, bbox_inches="tight")
    plt.close(fig)


def run(args: argparse.Namespace) -> None:
    results_dir = Path(args.results)
    out_dir = Path(args.out) if args.out else results_dir / "paper_figures"
    out_dir.mkdir(parents=True, exist_ok=True)

    summary_path = results_dir / "summary_timeseries.csv"
    corr_path = results_dir / "correlation_summary.csv"
    if not summary_path.exists():
        raise FileNotFoundError(f"Missing {summary_path}. Run run_paper_batch.py first.")
    summary = pd.read_csv(summary_path)
    corr = pd.read_csv(corr_path) if corr_path.exists() else pd.DataFrame()

    make_fig1_snapshots(results_dir, out_dir)
    make_fig2_histograms_scenario3(results_dir, out_dir)
    make_fig3_entropy_comparison(summary, out_dir)
    make_fig4_shape_weights(summary, out_dir)
    make_fig5_ablation_correlations(corr, out_dir)
    make_fig6_scenario4_freezing(summary, out_dir)

    print(f"Figures written to: {out_dir}")


def build_arg_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Make paper figures from batch results.")
    p.add_argument("--results", default="results_paper", help="Directory generated by run_paper_batch.py")
    p.add_argument("--out", default=None, help="Figure output directory. Defaults to <results>/paper_figures")
    return p


if __name__ == "__main__":
    run(build_arg_parser().parse_args())
